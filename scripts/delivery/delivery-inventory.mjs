import { lstat, open, opendir, readFile, realpath } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { isDeepStrictEqual } from 'node:util';

import { compareCodePoints } from '../lib/deterministic-order.mjs';
import { createError } from '../lib/errors.mjs';
import { parseRestrictedYaml } from '../lib/markdown.mjs';
import { isSafeLocator } from '../lib/reference-safety.mjs';
import { fail, ok } from '../lib/result.mjs';
import { validateJson } from '../lib/validate-json.mjs';
import { activeDeliveryPair, archivedDeliveryPair } from './delivery-layout.mjs';

const MAX_ENTRIES = 2000;
const MAX_DEPTH = 4;
const MAX_FRONTMATTER_BYTES = 65_536;
const GENERATED_NOTICE = '<!-- Generated by Project Lifecycle from validated active alignment state; do not edit. -->\n';
const INDEX_NOTICE = '<!-- Generated by Project Lifecycle from validated delivery Frontmatter; do not edit. -->\n';
const PHASE_KINDS = Object.freeze({
  architecture: 'architecture',
  batches: 'batch',
  closure: 'closure-summary',
  guidance: 'guidance',
  'test-reports': 'test-report',
});
const failure = (code, path, message) => fail([createError(code, path, message)]);
const inside = (root, candidate) => {
  const fromRoot = relative(root, candidate);
  return fromRoot === '' || (fromRoot !== '..' && !fromRoot.startsWith(`..${sep}`) && !isAbsolute(fromRoot));
};
const languageOf = (name) => name.endsWith('-en.md') ? 'en' : 'zh-CN';
const artifactIdOf = (name) => name.replace(/-en\.md$/u, '').replace(/\.md$/u, '');
const canonicalDirectory = (locator) => /^(?:delivery|archive\/delivery)\/(?:feedback|prds|non-prd)(?:\/[a-z][a-z0-9-]*(?:\/(?:architecture|batches|closure|guidance|test-reports))?)?$/u.test(locator)
  || locator === 'delivery/views';
const canonicalIndex = (locator) => /^delivery\/(?:INDEX(?:-en)?\.md|(?:prds|non-prd)\/[a-z][a-z0-9-]*\/INDEX(?:-en)?\.md)$/u.test(locator);

const readPrefix = async (path) => {
  const handle = await open(path, 'r');
  try {
    const buffer = Buffer.alloc(MAX_FRONTMATTER_BYTES + 1);
    let total = 0;
    while (total < buffer.length) {
      const { bytesRead } = await handle.read(buffer, total, buffer.length - total, total);
      if (bytesRead === 0) break;
      total += bytesRead;
      const source = buffer.subarray(0, total).toString('utf8').replaceAll('\r\n', '\n');
      const closing = source.indexOf('\n---\n', 4);
      if (source.startsWith('---\n') && closing !== -1
        && Buffer.byteLength(source.slice(0, closing + 5)) <= MAX_FRONTMATTER_BYTES) {
        return source.slice(0, closing + 5);
      }
    }
    throw new Error('Frontmatter is missing or unbounded.');
  } finally {
    await handle.close();
  }
};

const parseFrontmatter = (source) => {
  const normalized = source.replaceAll('\r\n', '\n');
  const closing = normalized.indexOf('\n---\n', 4);
  if (!normalized.startsWith('---\n') || closing === -1) return null;
  const parsed = parseRestrictedYaml(normalized.slice(4, closing), '/frontmatter');
  if (!parsed.ok || !validateJson('delivery-frontmatter', parsed.value).ok
    || parsed.value.schema_version !== 2) return null;
  return parsed.value;
};

const classify = (locator) => {
  const archived = locator.startsWith('archive/delivery/');
  const prefix = archived ? 'archive/delivery/' : 'delivery/';
  const rest = locator.slice(prefix.length);
  const feedback = /^feedback\/([a-z][a-z0-9-]*\.md)$/u.exec(rest);
  if (feedback) return { archived, artifactId: artifactIdOf(feedback[1]), ownerKind: null, ownerId: null, expectedKind: 'feedback' };
  const owner = /^(prds|non-prd)\/([a-z][a-z0-9-]*)\/(?:([a-z-]+)\/)?([a-z][a-z0-9-]*\.md)$/u.exec(rest);
  if (!owner) return null;
  const ownerKind = owner[1] === 'prds' ? 'prd' : 'non-prd-delivery';
  const phase = owner[3] ?? null;
  return {
    archived,
    artifactId: artifactIdOf(owner[4]),
    ownerKind,
    ownerId: owner[2],
    expectedKind: phase === null ? ownerKind : PHASE_KINDS[phase] ?? null,
  };
};

const itemFromPair = (pair) => ({
  artifact_id: pair.en.frontmatter.artifact_id,
  artifact_kind: pair.en.frontmatter.artifact_kind,
  ...(pair.en.frontmatter.owner_artifact_id
    ? { owner_artifact_id: pair.en.frontmatter.owner_artifact_id }
    : {}),
  retention_tier: pair.en.frontmatter.retention_tier,
  frontmatter: pair.en.frontmatter,
  locators: { en: pair.en.locator, 'zh-CN': pair['zh-CN'].locator },
});

export const collectDeliveryInventory = async ({ lifecycleRoot: rootValue, overlays = {} } = {}) => {
  if (typeof rootValue !== 'string' || !isAbsolute(rootValue)
    || overlays === null || typeof overlays !== 'object' || Array.isArray(overlays)) {
    return failure('DELIVERY_INVENTORY_INVALID', '/', 'A bounded lifecycle root and overlay map are required.');
  }
  let lifecycleRoot;
  try {
    const state = await lstat(resolve(rootValue));
    lifecycleRoot = await realpath(resolve(rootValue));
    if (!state.isDirectory() || state.isSymbolicLink()) throw new Error('Regular lifecycle root required.');
  } catch {
    return failure('DELIVERY_INVENTORY_INVALID', '/lifecycleRoot', 'A regular lifecycle root is required.');
  }

  const sources = new Map();
  let entryCount = 0;
  const readDirectory = async (directory) => {
    const entries = [];
    const handle = await opendir(directory);
    for await (const entry of handle) {
      entries.push(entry);
      if (entryCount + entries.length > MAX_ENTRIES) throw new Error('Delivery tree is unbounded.');
    }
    entries.sort((left, right) => compareCodePoints(left.name, right.name));
    return entries;
  };
  const scan = async (rootLocator) => {
    const lexical = join(lifecycleRoot, rootLocator);
    let root;
    try {
      const state = await lstat(lexical);
      root = await realpath(lexical);
      if (!state.isDirectory() || state.isSymbolicLink() || !inside(lifecycleRoot, root)) throw new Error('Unsafe delivery root.');
    } catch (error) {
      if (error.code === 'ENOENT') return;
      throw error;
    }
    const visit = async (directory, relativeDirectory, depth) => {
      if (depth > MAX_DEPTH) throw new Error('Delivery tree exceeds the managed depth.');
      for (const entry of await readDirectory(directory)) {
        entryCount += 1;
        if (entryCount > MAX_ENTRIES || entry.isSymbolicLink()) throw new Error('Delivery tree is unsafe or unbounded.');
        const path = join(directory, entry.name);
        const locator = `${rootLocator}/${relativeDirectory ? `${relativeDirectory}/` : ''}${entry.name}`;
        if (entry.isDirectory()) {
          if (!canonicalDirectory(locator)) throw new Error('Delivery tree contains an unknown directory.');
          await visit(path, relativeDirectory ? `${relativeDirectory}/${entry.name}` : entry.name, depth + 1);
        }
        else if (entry.isFile()) {
          const physical = await realpath(path);
          if (!inside(lifecycleRoot, physical)) throw new Error('Delivery file escapes lifecycle root.');
          const state = await lstat(physical);
          sources.set(locator, { path: physical, size: state.size });
        } else throw new Error('Unsupported delivery entry.');
      }
    };
    await visit(root, '', 0);
  };

  try {
    await scan('delivery');
    await scan('archive/delivery');
    for (const [locator, source] of Object.entries(overlays)) {
      if (!isSafeLocator(locator) || typeof source !== 'string'
        || !(locator.startsWith('delivery/') || locator.startsWith('archive/delivery/'))) {
        throw new Error('Invalid delivery overlay.');
      }
      sources.set(locator, { overlay: source });
    }
  } catch {
    return failure('DELIVERY_INVENTORY_INVALID', '/delivery', 'Delivery inventory could not be collected safely.');
  }

  const markerSource = sources.get('delivery/layout.json');
  if (!markerSource) {
    return failure('DELIVERY_LAYOUT_MIGRATION_REQUIRED', '/delivery/layout.json', 'Delivery layout v2 marker is required.');
  }
  try {
    const source = markerSource.overlay ?? await readFile(markerSource.path, 'utf8');
    if (!validateJson('delivery-layout', JSON.parse(source)).ok) throw new Error('Invalid layout marker.');
  } catch {
    return failure('DELIVERY_LAYOUT_MIGRATION_REQUIRED', '/delivery/layout.json', 'Delivery layout v2 marker is invalid.');
  }

  const ignored = new Set([
    'delivery/layout.json', 'delivery/INDEX-en.md', 'delivery/INDEX.md',
  ]);
  const viewLocators = ['delivery/views/alignment-review-en.md', 'delivery/views/alignment-review.md'];
  const presentViews = viewLocators.map((locator) => sources.has(locator));
  if (presentViews[0] !== presentViews[1]) {
    return failure('DELIVERY_INVENTORY_PAIR_INVALID', '/delivery/views', 'Generated delivery views require both languages.');
  }
  if (presentViews[0]) {
    for (const locator of viewLocators) {
      const source = sources.get(locator);
      const text = source.overlay ?? (source.size <= 131_072
        ? await readFile(source.path, 'utf8').catch(() => null)
        : null);
      if (typeof text !== 'string' || Buffer.byteLength(text) > 131_072
        || !text.startsWith(GENERATED_NOTICE)) {
        return failure('DELIVERY_INVENTORY_INVALID', `/${locator}`, 'Generated delivery view locator is occupied.');
      }
      ignored.add(locator);
    }
  }
  for (const [locator, source] of sources) {
    if (!/\/(?:INDEX-en\.md|INDEX\.md)$/u.test(locator)) continue;
    if (!canonicalIndex(locator)) {
      return failure('DELIVERY_INVENTORY_INVALID', `/${locator}`, 'Delivery index locator is not canonical.');
    }
    const content = source.overlay ?? (source.size <= 131_072
      ? await readFile(source.path, 'utf8').catch(() => null)
      : null);
    if (typeof content !== 'string' || !content.startsWith(INDEX_NOTICE)) {
      return failure('DELIVERY_INVENTORY_INVALID', `/${locator}`, 'Delivery index locator is occupied.');
    }
    ignored.add(locator);
  }

  const grouped = new Map();
  for (const [locator, source] of [...sources.entries()].sort(([left], [right]) => compareCodePoints(left, right))) {
    if (ignored.has(locator)) continue;
    const descriptor = classify(locator);
    if (!descriptor || descriptor.expectedKind === null) {
      return failure('DELIVERY_INVENTORY_INVALID', `/${locator}`, 'Delivery contains an unknown managed file.');
    }
    const raw = source.overlay ?? await readPrefix(source.path).catch(() => null);
    const metadata = typeof raw === 'string' && Buffer.byteLength(raw) <= 262_144
      ? parseFrontmatter(raw)
      : null;
    if (!metadata || metadata.artifact_id !== descriptor.artifactId
      || metadata.artifact_kind !== descriptor.expectedKind
      || (descriptor.ownerId !== null && metadata.owner_artifact_id !== descriptor.ownerId)) {
      return failure('DELIVERY_INVENTORY_PATH_MISMATCH', `/${locator}`, 'Delivery path and Frontmatter ownership must match.');
    }
    const expected = descriptor.archived
      ? archivedDeliveryPair(metadata, { ownerKind: descriptor.ownerKind })
      : activeDeliveryPair(metadata, { ownerKind: descriptor.ownerKind });
    if (!Object.values(expected).includes(locator)) {
      return failure('DELIVERY_INVENTORY_PATH_MISMATCH', `/${locator}`, 'Delivery locator is not canonical for its owner.');
    }
    const key = `${descriptor.archived ? 'archive' : 'active'}:${metadata.artifact_id}`;
    const pair = grouped.get(key) ?? {};
    const language = languageOf(locator);
    if (pair[language]) return failure('DELIVERY_INVENTORY_DUPLICATE', `/${locator}`, 'Delivery artifact language is duplicated.');
    pair[language] = { language, locator, frontmatter: metadata };
    grouped.set(key, pair);
  }

  const activeItems = [];
  const archivedItems = [];
  const activePairs = [];
  const archivedPairs = [];
  const artifactIds = new Set();
  for (const [key, pair] of grouped) {
    if (!pair.en || !pair['zh-CN'] || !isDeepStrictEqual(pair.en.frontmatter, pair['zh-CN'].frontmatter)) {
      return failure('DELIVERY_INVENTORY_PAIR_INVALID', `/${key}`, 'Delivery artifacts require one matching bilingual pair.');
    }
    const item = itemFromPair(pair);
    if (artifactIds.has(item.artifact_id)) {
      return failure('DELIVERY_INVENTORY_DUPLICATE', `/${item.artifact_id}`, 'Delivery artifact IDs must be globally unique.');
    }
    artifactIds.add(item.artifact_id);
    if (key.startsWith('archive:')) {
      archivedItems.push(item);
      archivedPairs.push(pair.en, pair['zh-CN']);
    } else {
      activeItems.push(item);
      activePairs.push(pair.en, pair['zh-CN']);
    }
  }
  const sortItems = (values) => values.sort((left, right) => compareCodePoints(left.artifact_id, right.artifact_id));
  sortItems(activeItems);
  sortItems(archivedItems);
  const owners = sortItems(activeItems.filter(({ artifact_kind: kind }) => ['prd', 'non-prd-delivery'].includes(kind)));
  const byOwner = {};
  const archivedByOwner = {};
  for (const owner of owners) byOwner[owner.artifact_id] = { owner, assets: [] };
  for (const item of archivedItems) {
    if (!item.owner_artifact_id) continue;
    archivedByOwner[item.owner_artifact_id] ??= { owner_artifact_id: item.owner_artifact_id, assets: [] };
    archivedByOwner[item.owner_artifact_id].assets.push(item);
  }
  const retainedOwnerIds = new Set(Object.values(archivedByOwner)
    .filter(({ owner_artifact_id: ownerId, assets }) => assets.some(({ artifact_id: id, artifact_kind: kind }) => (
      id === ownerId && ['prd', 'non-prd-delivery'].includes(kind)
    )))
    .map(({ owner_artifact_id: ownerId }) => ownerId));
  for (const item of activeItems) {
    if (!item.owner_artifact_id) continue;
    if (!byOwner[item.owner_artifact_id]) {
      if (item.artifact_kind === 'closure-summary' && retainedOwnerIds.has(item.owner_artifact_id)) continue;
      return failure('DELIVERY_INVENTORY_OWNER_MISSING', `/${item.artifact_id}`, 'Every active owned asset requires one active physical owner.');
    }
    byOwner[item.owner_artifact_id].assets.push(item);
  }
  for (const entry of Object.values(byOwner)) sortItems(entry.assets);
  for (const entry of Object.values(archivedByOwner)) sortItems(entry.assets);
  return ok({
    layout_version: 2,
    feedbacks: sortItems(activeItems.filter(({ artifact_kind: kind }) => kind === 'feedback')),
    owners,
    closed_summaries: sortItems([...activeItems, ...archivedItems]
      .filter(({ artifact_kind: kind }) => kind === 'closure-summary')),
    views: presentViews[0] ? [{
      artifact_id: 'alignment-review',
      locators: { en: viewLocators[0], 'zh-CN': viewLocators[1] },
    }] : [],
    by_owner: byOwner,
    archived_by_owner: archivedByOwner,
    pairs: activePairs.sort((left, right) => compareCodePoints(left.locator, right.locator)),
    archived_pairs: archivedPairs.sort((left, right) => compareCodePoints(left.locator, right.locator)),
  });
};
